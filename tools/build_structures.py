#!/usr/bin/env python3
"""Turns the structure OBJ models (well, blacksmith, archery target, camping scene) into js/structures.js: compact static meshes.

usage: python3 tools/build_structures.py <structures-dir>
<structures-dir> holds Well/, Blacksmith/, archery_target/, camping_scene_3d_model/ (each with the .obj and *_basecolor.jpg).
Every part is scaled to the size the game uses for that building and moved so that its base centre is the origin (y up, front = +z)."""
import sys, os, glob, base64, io, json
import numpy as np
from PIL import Image
sys.path.insert(0, os.path.dirname(__file__))
from build_models import parse_obj, b64

def components(pos, tri):
    key = {}; vid = np.array([key.setdefault(tuple(p), len(key)) for p in np.round(pos, 4)]); parent = list(range(len(key)))
    def f(a):
        while parent[a] != a: parent[a] = parent[parent[a]]; a = parent[a]
        return a
    for a, b, c in vid[tri]: parent[f(b)] = f(a); parent[f(c)] = f(a)
    comp = {}
    for ti, t in enumerate(vid[tri]): comp.setdefault(f(t[0]), []).append(ti)
    return list(comp.values())

def pack(pos, uv, nor, tri_idx, tex):
    vs, inv = np.unique(tri_idx.ravel(), return_inverse=True)
    return {'n': len(vs), 'pos': pos[vs], 'uv': uv[vs], 'nor': nor[vs], 'idx': inv.astype(np.uint16), 'tex': tex}

def emit(part, scale, rot_y=0.0, center=True):
    P = part['pos'].copy(); N = part['nor'].copy()
    if rot_y:
        c, s = np.cos(rot_y), np.sin(rot_y); R = np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]]); P = P @ R.T; N = N @ R.T
    lo, hi = P.min(axis=0), P.max(axis=0)
    P = (P - [(lo[0] + hi[0]) / 2 if center else 0, lo[1], (lo[2] + hi[2]) / 2 if center else 0]) * scale
    return {'n': part['n'], 'pos': b64(np.round(P * 10000).astype(np.int16)), 'uv': b64(np.round(part['uv'] * 65535).astype(np.uint16)),
            'nor': b64(np.round(N / np.maximum(np.linalg.norm(N, axis=1, keepdims=True), 1e-9) * 127).astype(np.int8)), 'idx': b64(part['idx']),
            'tex': part['tex'], 'size': [round(float(x), 2) for x in (P.max(axis=0) - P.min(axis=0))]}

def load(folder):
    obj = glob.glob(os.path.join(folder, '*.obj'))[0]; tex = glob.glob(os.path.join(folder, '*basecolor.jpg'))[0]
    pos, uv, nor, idx = parse_obj(obj)
    im = Image.open(tex).convert('RGB').resize((512, 512), Image.LANCZOS); buf = io.BytesIO(); im.save(buf, 'JPEG', quality=82)
    return pos, uv, nor, idx.reshape(-1, 3).astype(int), 'data:image/jpeg;base64,' + base64.b64encode(buf.getvalue()).decode()

def main():
    root = sys.argv[1]; out = {}
    for key, folder, width in (('well', 'Well', 2.5), ('smith', 'Blacksmith', 4.6), ('range', 'archery_target', 5.4)):
        pos, uv, nor, tri, tex = load(os.path.join(root, folder))
        part = pack(pos, uv, nor, tri, tex); w = pos[:, 0].max() - pos[:, 0].min()
        out[key] = emit(part, width / w); print(key.ljust(8), out[key]['n'], 'verts size', out[key]['size'])
    pos, uv, nor, tri, tex = load(os.path.join(root, 'camping_scene_3d_model'))
    for tis in components(pos, tri):
        p = pos[np.unique(tri[tis].ravel())]; lo, hi = p.min(axis=0), p.max(axis=0); cx, cy = (lo[0] + hi[0]) / 2, (lo[1] + hi[1]) / 2
        if len(tis) > 500: name, width = 'campfire', 2.0                  # 모닥불: 돌 테두리 + 장작 (불꽃은 게임이 그린다)
        elif cx < 0 and cy < 0.2: name, width = 'tent', 3.6               # 텐트
        elif cx > 0 and cy > 0.4: name, width = 'fence', 2.4              # 나무 목책
        elif cx > 0 and cy < 0.2: name, width = 'wall', 3.0               # 벽돌 성벽
        else: continue                                                      # 나무: 게임에 이미 있다
        part = pack(pos, uv, nor, tri[tis].ravel().reshape(-1, 3), tex)
        part['tex'] = tex
        out[name] = emit(part, width / (hi[0] - lo[0])); print(name.ljust(8), out[name]['n'], 'verts size', out[name]['size'])
    # 텍스처는 한 번만 저장한다 (캠프 장면 부품은 같은 텍스처)
    texs = {}
    for k, v in out.items():
        t = v.pop('tex'); texs.setdefault(t, 't%d' % len(texs)); v['t'] = texs[t]
    js = '// Generated by tools/build_structures.py - static building meshes (AI-generated models by the project owner). Do not edit by hand.\nconst STRUCT_MODELS = ' + json.dumps({'parts': out, 'tex': {v: k for k, v in texs.items()}}, separators=(',', ':')) + ';\n'
    open(os.path.join(os.path.dirname(__file__), '..', 'js', 'structures.js'), 'w').write(js)
    print('wrote js/structures.js', len(js) // 1024, 'KB')

if __name__ == '__main__': main()
